#!/usr/bin/env bash
# Regenerate Apache's Cloudflare mod_remoteip snippet from Cloudflare's
# published ranges. Run on Apache servers behind Cloudflare only, e.g. weekly
# from cron:
#   0 4 * * 1 root /usr/local/sbin/cloudflare-update-ips-apache.sh
# Works on Debian/Ubuntu (apache2, conf-available + a2enconf) and RHEL/Fedora
# (httpd, conf.d). Requires mod_remoteip to be enabled (a2enmod remoteip).
# Usage: cloudflare-update-ips-apache.sh [output-file]
set -euo pipefail

if [[ -d /etc/apache2/conf-available ]]; then
  OUT=${1:-/etc/apache2/conf-available/cloudflare-remoteip.conf}
  SERVICE=apache2
  DEBIAN=1
else
  OUT=${1:-/etc/httpd/conf.d/cloudflare-remoteip.conf}
  SERVICE=httpd
  DEBIAN=0
fi
BASE=https://www.cloudflare.com
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

v4=$(curl -fsS --max-time 20 "$BASE/ips-v4")
v6=$(curl -fsS --max-time 20 "$BASE/ips-v6")

# Refuse to write a snippet that is obviously wrong (empty or HTML error page).
grep -qE '^[0-9.]+/[0-9]+$' <<<"$v4" || { echo "unexpected ips-v4 response" >&2; exit 1; }
grep -qE '^[0-9a-f:]+/[0-9]+$' <<<"$v6" || { echo "unexpected ips-v6 response" >&2; exit 1; }

{
  echo "# Generated by cloudflare-update-ips-apache.sh. Do not edit."
  echo "RemoteIPHeader CF-Connecting-IP"
  while read -r r; do [[ $r ]] && echo "RemoteIPTrustedProxy $r"; done <<<"$v4"
  while read -r r; do [[ $r ]] && echo "RemoteIPTrustedProxy $r"; done <<<"$v6"
} >"$tmp"

if [[ -f $OUT ]] && cmp -s "$tmp" "$OUT"; then exit 0; fi

# Keep the old snippet so a config that fails configtest is rolled back.
[[ -f $OUT ]] && cp -p "$OUT" "$OUT.bak"
install -m 644 "$tmp" "$OUT"
if (( DEBIAN )); then a2enconf -q "$(basename "$OUT" .conf)"; fi
if ! apachectl configtest 2>/dev/null; then
  echo "apachectl configtest failed, restoring previous snippet" >&2
  if [[ -f $OUT.bak ]]; then
    mv "$OUT.bak" "$OUT"
  else
    if (( DEBIAN )); then a2disconf -q "$(basename "$OUT" .conf)" || true; fi
    rm -f "$OUT"
  fi
  exit 1
fi
rm -f "$OUT.bak"
systemctl reload "$SERVICE"
echo "updated $OUT"
