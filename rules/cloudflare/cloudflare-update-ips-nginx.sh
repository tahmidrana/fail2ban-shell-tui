#!/usr/bin/env bash
# Regenerate nginx's Cloudflare real-IP snippet from Cloudflare's published
# ranges. Run on nginx servers behind Cloudflare only, e.g. weekly from cron:
#   0 4 * * 1 root /usr/local/sbin/cloudflare-update-ips-nginx.sh
# Usage: cloudflare-update-ips-nginx.sh [output-file]
set -euo pipefail

OUT=${1:-/etc/nginx/conf.d/cloudflare-realip.conf}
BASE=https://www.cloudflare.com
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

v4=$(curl -fsS --max-time 20 "$BASE/ips-v4")
v6=$(curl -fsS --max-time 20 "$BASE/ips-v6")

# Refuse to write a snippet that is obviously wrong (empty or HTML error page).
grep -qE '^[0-9.]+/[0-9]+$' <<<"$v4" || { echo "unexpected ips-v4 response" >&2; exit 1; }
grep -qE '^[0-9a-f:]+/[0-9]+$' <<<"$v6" || { echo "unexpected ips-v6 response" >&2; exit 1; }

{
  echo "# Generated by cloudflare-update-ips-nginx.sh. Do not edit."
  while read -r r; do [[ $r ]] && echo "set_real_ip_from $r;"; done <<<"$v4"
  while read -r r; do [[ $r ]] && echo "set_real_ip_from $r;"; done <<<"$v6"
  echo "real_ip_header CF-Connecting-IP;"
} >"$tmp"

if [[ -f $OUT ]] && cmp -s "$tmp" "$OUT"; then exit 0; fi

# Keep the old snippet so a config that fails nginx -t is rolled back.
[[ -f $OUT ]] && cp -p "$OUT" "$OUT.bak"
install -m 644 "$tmp" "$OUT"
if ! nginx -t 2>/dev/null; then
  echo "nginx -t failed, restoring previous snippet" >&2
  if [[ -f $OUT.bak ]]; then mv "$OUT.bak" "$OUT"; else rm -f "$OUT"; fi
  exit 1
fi
rm -f "$OUT.bak"
systemctl reload nginx
echo "updated $OUT"
